import {test} from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import {createPlan,addNode,changePlan} from '../public/planning-model.js';
import {addDecision} from '../public/decision-model.js';

test('finalization memo and acknowledgment never trap tab navigation, even when finalization or saving fails',async t=>{
 const {window}=new JSDOM('<main id="planning-root"></main>',{url:'http://127.0.0.1:4173'});
 for(const key of ['window','document','localStorage','sessionStorage','location','FormData'])globalThis[key]=key==='window'?window:window[key];
 const {mountPlanner}=await import('../public/planning.js?v=0.9.5');
 const project={id:'navigation',name:'Navigation',description:'Drafts survive navigation',instructions:''};
 project.planning=createPlan(project);
 const work=addNode(project.planning,project.planning.rootId,{title:'작업',instructions:'실행한다',criteria:''});
 addDecision(project.planning,{type:'question',question:'나중에 결정할까요?',nodeIds:[work.id],blocking:true});
 const root=document.querySelector('#planning-root'),messages=[];
 let failSave=true;
 const planner=mountPlanner(root,{project,revision:0,icon:()=>'',toast:m=>messages.push(m),exportProject(){},save:async()=>{if(failSave)throw new Error('저장 실패');return 1;}});
 t.after(()=>{planner.destroy();window.close();});
 const find=selector=>{const element=root.querySelector(selector);assert.ok(element,selector);return element;};
 const click=selector=>planner.onClick({target:find(selector),preventDefault(){}});
 const fill=(selector,value)=>{const element=find(selector);element.value=value;element.dispatchEvent(new window.Event('input',{bubbles:true}));};
 const check=value=>{const element=find('#decision-finalize [name="ack"]');element.checked=value;element.dispatchEvent(new window.Event('change',{bubbles:true}));};
 const submit=()=>planner.onSubmit({target:find('#decision-finalize'),preventDefault(){}});
 await click('[data-pa="page-finalize"]');
 assert.equal(find('#decision-finalize .primary').disabled,true);
 fill('#decision-finalize [name="note"]','기준을 채운 뒤 확정');check(true);check(false);
 assert.equal(planner.decisionDirty,false);
 await click('[data-pa="page-board"]');assert.equal(planner.page,'board');
 await click('[data-pa="page-decisions"]');assert.equal(planner.page,'decisions');
 await click('[data-pa="page-finalize"]');
 assert.equal(find('#decision-finalize [name="note"]').value,'기준을 채운 뒤 확정');
 assert.equal(find('#decision-finalize [name="ack"]').checked,false);
 check(true);
 planner.plan=changePlan(planner.plan,'완료 기준',p=>{p.nodes.find(n=>n.id===work.id).criteria='결과 확인';});
 planner.render();assert.equal(find('#decision-finalize [name="ack"]').checked,false,'a changed plan needs fresh acknowledgment');
 assert.equal(find('#decision-finalize .primary').disabled,false);
 check(true);await submit();assert.equal(planner.plan.baselines.length,0);
 await click('[data-pa="page-decisions"]');await click('[data-pa="page-finalize"]');
 assert.equal(find('#decision-finalize [name="note"]').value,'기준을 채운 뒤 확정');
 assert.equal(find('#decision-finalize [name="ack"]').checked,true,'failed save preserves acknowledgment');
 // A new planner instance restores this tab's memo without applying any decision.
 delete planner.finalizationDraft;planner.render();
 assert.equal(find('#decision-finalize [name="note"]').value,'기준을 채운 뒤 확정');
 failSave=false;await submit();assert.equal(planner.plan.baselines.length,1);
 assert.equal(planner.plan.items[0].answer,'');assert.equal(planner.plan.items[0].status,'answer');
 assert.equal(root.querySelector('#decision-finalize .primary'),null,'an already-finalized plan shows status, not a disabled next-version action');
 assert.equal(find('#decision-finalize [name="note"]').value,'');
 await click('[data-pa="page-board"]');assert.equal(planner.page,'board');
 await click('[data-pa="page-finalize"]');
 fill('#decision-finalize [name="note"]','지울 메모');check(true);
 await click('[data-dec="clear-finalization"]');
 assert.equal(find('#decision-finalize [name="note"]').value,'');assert.equal(find('#decision-finalize [name="ack"]').checked,false);
 assert.ok(!messages.some(m=>m.includes('먼저 저장')),'finalization controls must not trigger answer/handoff dirty guards');
});
