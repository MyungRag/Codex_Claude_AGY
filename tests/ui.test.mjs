import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {JSDOM} from 'jsdom';
import {IDBFactory} from 'fake-indexeddb';
import {validateProject} from '../public/model.js';

const until=async condition=>{for(let n=0;n<100;n++){if(await condition())return;await new Promise(r=>setTimeout(r,10));}assert.fail('UI did not reach the expected state');};

test('UI: current PC/Git editor, folder selection/cancel, and No/Yes deletion preserve the right data',async()=>{
  const dom=new JSDOM(await readFile(new URL('../public/index.html',import.meta.url),'utf8'),{url:'http://127.0.0.1:4173'});
  const {window}=dom;
  for(const key of ['window','document','localStorage','history','location','FormData'])globalThis[key]=key==='window'?window:window[key];
  globalThis.indexedDB=new IDBFactory();
  globalThis.BroadcastChannel=undefined;
  globalThis.fetch=async()=>({ok:true,headers:{get:()=> 'application/json'},json:async()=>({folderPicker:'browser'})});
  // jsdom has no operating-system dialogs; only that platform surface is stubbed.
  window.HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','');this.querySelector('[autofocus]')?.focus();};
  window.HTMLDialogElement.prototype.close=function(){this.removeAttribute('open');this.dispatchEvent(new window.Event('close'));};
  let folderCalls=0;
  window.showDirectoryPicker=async()=>{folderCalls++;return {kind:'directory',name:'선택한 KAF'};};
  const storage=await import('../public/storage.js?v=0.8.0');
  await storage.openStore();
  const project=validateProject({id:'kaf',name:'KAF',paths:{current:'C:\\KAF'},instructions:'Keep instructions',files:[{name:'reference.txt',data:'aGk='}]});
  const keep=validateProject({id:'keep',name:'다른 프로젝트'});
  await storage.saveState({projects:[project,keep]},0);
  await import('../public/app.js');
  const $=selector=>document.querySelector(selector);
  const click=selector=>{const el=$(selector);assert.ok(el,selector);el.click();};
  click('.recent-row [data-action="open"][data-id="kaf"]');
  await until(()=>location.hash==='#kaf');
  click('[data-action="edit"][data-id="kaf"]');
  assert.equal(document.querySelectorAll('#path-current').length,1);
  assert.equal($('#path-office'),null);assert.equal($('#path-home'),null);assert.equal($('#pc-select'),null);
  assert.ok($('#path-current').parentElement.querySelector('[data-action="pick-folder"]'));
  $('#git-url').value='git@github.com:example/KAF.git';
  click('[data-action="pick-folder"]');
  await until(()=>!$('#save-project').disabled);
  assert.equal(folderCalls,1);assert.equal($('#path-current').value,'');
  assert.match($('#folder-selection-current').textContent,/선택한 KAF/);
  $('#project-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>!$('dialog[open]'));
  await until(()=>$('#main').textContent.includes('git@github.com:example/KAF.git'));
  let saved=(await storage.readState()).projects.find(p=>p.id==='kaf');
  assert.equal(saved.gitUrl,'git@github.com:example/KAF.git');
  assert.equal(saved.paths.current,'');assert.equal(saved.folderNames.current,'선택한 KAF');
  assert.equal(saved.instructions,'Keep instructions');assert.deepEqual(saved.files,project.files);
  click('[data-action="edit"][data-id="kaf"]');
  $('#path-current').value='D:\\KAF';$('#path-current').dispatchEvent(new window.Event('input',{bubbles:true}));
  window.showDirectoryPicker=async()=>{throw new window.DOMException('cancelled','AbortError');};
  click('[data-action="pick-folder"]');await until(()=>!$('#save-project').disabled);
  assert.equal($('#path-current').value,'D:\\KAF');
  $('#project-form').dispatchEvent(new window.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>!$('dialog[open]'));await until(async()=> (await storage.readState()).projects.find(p=>p.id==='kaf').paths.current==='D:\\KAF');
  click('.recent-row [data-action="delete"][data-id="kaf"]');
  assert.equal($('dialog h2').textContent,'정말 삭제하겠습니까?');
  assert.equal($('dialog [data-action="close-dialog"][autofocus]').textContent,'No');
  assert.equal($('dialog [data-action="confirm-delete"]').textContent,'Yes');
  click('dialog [data-action="close-dialog"][autofocus]');
  assert.equal((await storage.readState()).projects.length,2);
  assert.equal(location.hash,'#kaf');
  click('.recent-row [data-action="delete"][data-id="kaf"]');
  click('dialog [data-action="confirm-delete"]');
  await until(()=>!$('dialog[open]'));
  assert.equal(location.hash,'');
  assert.deepEqual((await storage.readState()).projects.map(p=>p.id),['keep']);
  assert.equal($('.recent-row [data-action="delete"][data-id="kaf"]'),null);
  assert.equal(localStorage.getItem('agent-desk-last-project'),'');
  assert.equal(document.querySelector('.nav-item .count').textContent,'1');
  window.close();
});
